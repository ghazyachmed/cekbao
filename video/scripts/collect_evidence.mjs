// Turns the real test and scenario output into src/generated/evidence.ts.
// Run from video/ after re-running the tests (see README):
//   node scripts/collect_evidence.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { execSync } from "node:child_process";

const root = new URL("../", import.meta.url).pathname;
const pytest = readFileSync(root + "public/evidence/pytest_live.txt", "utf8").split("\n");
const scen = readFileSync(root + "public/evidence/scenarios_live.txt", "utf8").split("\n");

const pick = [
  "test_approved_channel_match_allows_plan_only_after_confirmation",
  "test_conflicting_payee_blocks",
  "test_spoofed_and_manipulated_links_conflict",
  "test_prompt_injection_cannot_clear_a_request",
  "test_slip_without_ledger_record_is_unconfirmed_not_paid",
  "test_pdf_receipt_claiming_paid_does_not_yield_paid",
  "test_no_session_cannot_read_or_approve",
  "test_cross_user_access_denied",
  "test_reviewer_cannot_approve_or_create",
  "test_missing_csrf_token_rejected",
  "test_duplicate_approval_executes_once",
  "test_all_in_cost_exact_decimal",
  "test_disallowed_tool_falls_back_and_cannot_approve",
  "test_export_is_reproducible_and_matches_audit_log",
];
const testLines = [];
for (const name of pick) {
  const line = pytest.find((l) => l.includes(`::${name}`) && l.includes("PASSED"));
  if (!line) throw new Error(`test ${name} not found as PASSED in pytest_live.txt`);
  testLines.push(line.replace(/\s+\[\s*\d+%\]$/, "").trim());
}
const summary = pytest.find((l) => /=+ \d+ passed/.test(l));
const exit = pytest.find((l) => l.startsWith("PYTEST_EXIT_CODE="));
const platform = pytest.find((l) => l.startsWith("platform "));
const passed = Number(summary.match(/(\d+) passed/)[1]);
const scenSummary = scen.find((l) => l.startsWith("SUMMARY:"));
const scenExit = scen.find((l) => l.startsWith("SCENARIOS_EXIT_CODE="));
const [sPass, sTotal] = scenSummary.match(/(\d+)\/(\d+)/).slice(1).map(Number);
const scenChecks = scen.filter((l) => /\[PASS\]|\[FAIL\]/.test(l)).map((l) => l.trim());
const commit = execSync("git rev-parse HEAD", { cwd: root + ".." }).toString().trim();

const out = `// Generated by scripts/collect_evidence.mjs from public/evidence/*.txt. Do not edit by hand.
export const EVIDENCE = ${JSON.stringify({
  commit, platform, testLines, summary: summary.replace(/=/g, "").trim(), pytestExit: exit, passed,
  scenSummary, scenExit, scenPassed: sPass, scenTotal: sTotal, scenChecks,
}, null, 2)};
`;
writeFileSync(root + "src/generated/evidence.ts", out);
console.log(`evidence.ts: ${passed} passed, ${exit}, scenarios ${sPass}/${sTotal}, ${scenExit}, commit ${commit}`);
