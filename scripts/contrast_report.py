def tokens() -> dict[str, str]:
    return {m.group(1): m.group(2).lower() for m in re.finditer(r"--([a-z0-9-]+):\s*(#[0-9a-fA-F]{6})", TOKENS.read_text())}


def luminance(hex_color: str) -> float:
    def channel(c: int) -> float:
        s = c / 255
        return s / 12.92 if s <= 0.04045 else ((s + 0.055) / 1.055) ** 2.4
    r, g, b = (int(hex_color[i:i + 2], 16) for i in (1, 3, 5))
    return 0.2126 * channel(r) + 0.7152 * channel(g) + 0.0722 * channel(b)


def ratio(a: str, b: str) -> float:
    la, lb = sorted((luminance(a), luminance(b)), reverse=True)
    return (la + 0.05) / (lb + 0.05)


def main() -> int:
    tok = tokens()
    rows, failures = [], 0
    for fg, bg, need, where in PAIRS:
        r = ratio(tok[fg], tok[bg])
        ok = r >= need
        failures += 0 if ok else 1
        rows.append(f"| `--{fg}` {tok[fg]} | `--{bg}` {tok[bg]} | {r:.2f}:1 | {need}:1 | {'pass' if ok else 'FAIL'} | {where} |")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(
        "# Measured contrast (WCAG 2.2)\n\nGenerated by `scripts/contrast_report.py` from `policyguard/web/static/"
        "tokens.css`. Thresholds: 4.5:1 for normal text (SC 1.4.3), 3:1 for UI component boundaries and state "
        "indicators (SC 1.4.11). Ratios use the WCAG relative-luminance formula. A passing token pair does not prove "
        "that every screen passes; see `evidence/policyguard/ui/axe-*.json` for page audits.\n\n"
        "| Foreground | Background | Ratio | Needed | Result | Used for |\n|---|---|---|---|---|---|\n"
        + "\n".join(rows) + f"\n\nPairs: {len(rows)}. Failures: {failures}.\n")
    print(f"{len(rows)} pairs, {failures} failures -> {OUT.relative_to(ROOT)}")
    return 1 if failures else 0


