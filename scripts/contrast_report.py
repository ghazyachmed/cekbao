"""Measure WCAG 2.2 contrast for the colour pairs the PolicyGuard UI actually uses.

Reads the hex tokens from policyguard/web/static/tokens.css and writes docs/policyguard/CONTRAST.md.
Exit code 1 if any pair is below its threshold (4.5:1 text, 3:1 non-text and large text).
"""
from __future__ import annotations

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TOKENS = ROOT / "policyguard" / "web" / "static" / "tokens.css"
OUT = ROOT / "docs" / "policyguard" / "CONTRAST.md"

